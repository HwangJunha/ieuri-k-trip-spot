/// 피드 정렬 순서(2차 가이드 §3). **커뮤니티가 소유하는 도메인 enum이며** 서버의
/// 생성 enum(`Enum$PostSortOrder`)은 repository 밖으로 나가지 않는다(CLAUDE.md §3).
///
/// | 값 | 무엇이 보이나 | 순서 |
/// |---|---|---|
/// | [latest](기본) | 반경 안 글 **+ 장소 없이 쓴 글** | 최신순 |
/// | [distance] | 반경 안 장소에 붙은 글만 | 가까운 장소 순, 같은 장소끼리 최신순 |
///
/// **두 정렬의 커서 형식이 다르다** — 정렬을 바꾸면 커서를 버리고 첫 페이지부터
/// 다시 조회해야 하며, 이전 커서를 그대로 넘기면 서버가 `INVALID_INPUT`을 준다.
/// 피드 provider가 정렬을 family 인자로 두는 이유가 이것이다: 정렬이 바뀌면 다른
/// 인스턴스가 처음부터 로딩되므로 커서가 섞일 수 없다.
enum PostSortOrder {
  /// 기본값. 장소 없이 쓴 글도 함께 보인다.
  latest,

  /// 가까운 장소 순. **장소 없는 글은 빠진다** — 거리가 없어 어디에 둘지 정할 수
  /// 없기 때문이다. 좌표를 주지 않으면 [latest]처럼 동작하며 오류가 아니다.
  distance,
}
