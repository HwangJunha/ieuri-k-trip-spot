/// 둘러보기 탭의 두 화면(R5).
///
/// **토글은 제스처 표면 위 오버레이가 아니라 별도 헤더다**(설계 §1). 두 화면 모두
/// 전면 제스처를 쓰기 때문이다 — 추천은 스와이프 카드, 피드는 세로 스크롤. 토글을
/// 제스처 표면에 겹치면 토글 탭과 드래그·스크롤 시작이 같은 영역에서 경합한다.
///
/// 각 화면의 상태는 전환 후에도 유지되며(AC5-1), 한쪽의 실패가 다른 쪽을 막지
/// 않는다(AC5-3). 그 격리는 **두 화면이 서로 다른 provider를 보고 있고 이 열거형이
/// 어느 쪽을 그릴지만 정하기 때문에** 성립한다 — 토글이 상태를 소유하면 격리가
/// 깨진다.
enum DiscoverSegment {
  /// 기존 스와이프 추천(SPEC-0002/0006). **피드 도입이 추천을 대체하지 않는다**(AC5-2).
  recommendation,

  /// 세로 전면 스크롤 피드.
  feed,
}
