/// 구역의 인구 밀집 4단계(R7). 서버 `CongestionLevel` enum과 1:1로 맞춘다.
///
/// **표시 문자열이 아니라 식별자다**(POL-023). 화면에 쓸 문구는 l10n 키로 매핑하며
/// (`mapCongestion*`), 업스트림의 한국어 원문을 그대로 노출하지 않는다.
///
/// 기준은 절대 인원수가 아니라 **최근 28일 평균 대비 백분위**다(spec §4.1). 새벽에
/// 도심이 [relaxed]로 나오는 것은 정상 동작이다.
enum CongestionLevel {
  /// 여유 — 평균의 50% 이하.
  relaxed,

  /// 보통 — 50% 초과 75% 이하.
  normal,

  /// 약간 붐빔 — 75% 초과 100% 이하.
  slightlyCrowded,

  /// 붐빔 — 100% 초과.
  crowded,
}
