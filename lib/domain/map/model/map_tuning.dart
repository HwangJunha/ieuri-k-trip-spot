/// 지도 동작을 좌우하는 수치를 한곳에 모아 둔다. **전부 잠정값이다** —
/// spec §8의 미결 1·2·6·7번이며 실기기 측정으로 확정된다(설계 §9.2).
///
/// 한 파일에 모으는 이유는 측정 후 고칠 자리를 하나로 두기 위해서다. 값이 여러
/// 파일에 흩어지면 나중에 어느 것이 `[TBD]`였는지 되짚기 어렵다.
///
/// 확정되면 `[AMEND] SPEC-0014: ...`로 이슈에 회신한다.
abstract final class MapTuning {
  /// 유휴 판정 디바운스(R19). 지도가 멈춘 뒤 이 시간이 지나야 조회한다.
  ///
  /// 잠정 300ms — 손을 뗀 직후의 관성 스크롤이 잦아드는 데 통상 이 정도가 걸린다.
  /// 짧으면 관성 중에 조회가 나가 헛돌고, 길면 멈춘 뒤 빈 지도를 보는 시간이 늘어난다.
  static const Duration idleDebounce = Duration(milliseconds: 300);

  /// 뷰포트 확장 배율(R20). 화면 bbox를 이 배율로 넓혀 조회한다.
  ///
  /// 잠정 1.2배 — 화면 밖으로 각 변의 10%씩을 미리 받아 둔다.
  ///
  /// 처음엔 1.5배로 뒀다가 낮췄다. 넓힐수록 결과 수가 늘어 줌별 상한(R3)에 더 빨리
  /// 닿는데, 실기기에서 줌 14 기준 이미 상한 500건에 걸려 잘림 안내가 상시 떠 있었다
  /// (설계 §3.2가 감수한다고 한 대가가 실제로는 컸다). 재조회를 조금 더 하더라도
  /// 한 번에 받는 양을 줄이는 편이 체감이 낫다.
  static const double viewportExpansion = 1.2;

  /// **서버가 받는 줌의 최대값.** 이보다 큰 값을 보내면 `INVALID_ZOOM`으로 거절된다.
  ///
  /// 카카오 SDK의 줌은 21까지 올라가는데 서버 계약은 1~14다(`map_schema.graphql`).
  /// 그 차이를 모르고 SDK 줌을 그대로 보냈다가 확대할수록 마커가 하나도 안 오는
  /// 상태가 됐다 — 실기기에서 강남역을 봤을 때 "지도 확대 수준이 올바르지 않습니다"가
  /// 계속 찍혔다.
  ///
  /// 조회 직전에 [clampForServer]로 접는다.
  static const int serverMaxZoom = 14;

  /// 서버에 보낼 줌으로 접는다. 화면 표시용 줌은 그대로 두고 **요청 값만** 바꾼다 —
  /// 마커 게이트·폴리곤 게이트는 실제 화면 줌으로 판정해야 한다.
  static int clampForServer(int zoomLevel) => zoomLevel.clamp(1, serverMaxZoom);

  /// 혼잡도 폴리곤을 그리는 최소 줌(R25).
  ///
  /// 렌더링 기준이자 **호출량 상한 장치**다. 이 값 미만에서는 `seoulCongestion`을
  /// 호출조차 하지 않는다(설계 §5.1) — 일일 쿼터 1000건을 지키는 실질적 수단이다.
  ///
  /// 잠정 11 — 서울 전역이 한 화면에 들어오는 배율까지 커버한다(사용자 결정,
  /// 2026-08-10).
  ///
  /// 처음에는 14로 두었는데, 조금만 축소해도 폴리곤과 범례가 통째로 사라져 기능이
  /// 없는 것처럼 보였다. 서울 전역을 봐도 서버가 주는 구역은 최대 121곳이고 그마저
  /// bbox에 걸치는 것만 오므로, 호출량은 한 번의 조회로 같다 — 게이트를 낮춰도
  /// 쿼터 부담이 늘지 않는다.
  ///
  /// 그보다 더 축소하면(전국·동아시아) 서울이 화면의 점 하나가 되어 폴리곤을 그릴
  /// 의미가 없으므로 그때는 숨긴다.
  static const int polygonMinZoom = 11;

  /// 서버가 클러스터를 내려주는 상한 줌(R2). 이 값 이하에서 클러스터가 오고 초과하면
  /// 개별 마커가 온다.
  ///
  /// **판정은 서버가 한다.** 클라이언트는 `spots`/`clusters` 중 채워진 쪽을 그릴
  /// 뿐이며(설계 §4.2), 이 값은 클러스터를 탭했을 때 어디까지 확대할지를 정하는 데
  /// 쓴다.
  static const int clusterMaxZoom = 13;

  /// 개별 마커를 그리기 시작하는 최소 줌.
  ///
  /// **서버의 클러스터 임계값과 별개인 클라이언트 방어선이다.** 서버가 줌 14에서
  /// 개별 마커 500건을 내려주는 것이 관측됐는데, 마커 하나가 네이티브 왕복 1회라
  /// 500개를 그리는 동안 지도가 눈에 띄게 버벅이고 화면도 마커로 뒤덮인다.
  ///
  /// 이 값 미만에서는 개별 마커를 **그리지 않는다**. 클러스터가 함께 왔으면 그것을
  /// 그리고, 없으면 아무것도 그리지 않은 채 확대를 기다린다 — 잘림 안내(R23)가
  /// 이미 "확대하면 다 보인다"를 말하고 있어 사용자가 길을 잃지 않는다.
  ///
  /// **게이트를 두지 않는다.** 어느 줌에서든 마커를 그린다.
  ///
  /// 처음엔 저줌에서 서버가 클러스터를 줄 것으로 보고 개별 마커를 막았는데,
  /// 실측해 보니 **서버는 어느 줌에서도 클러스터를 주지 않는다**(zoom 10~14 전부
  /// `clusters: 0`, 개별 spot 500건). 게이트가 데이터를 막기만 하고 대신 보여줄
  /// 것이 없어, 넓게 보면 지도가 텅 비었다.
  ///
  /// 대신 **보관 상한**으로 다루므로(→[maxRetainedMarkers]) 넓은 뷰에서도
  /// 스무 개 남짓만 골고루 찍힌다.
  static const int markerMinZoom = 1;

  /// **한 번에 더해지는** 마커 수.
  ///
  /// **10개**(사용자 결정, 2026-08-10). 강남 한 화면에 500건이 오는데 다 찍으면
  /// 마커가 겹쳐 지도가 안 보인다. 사진 마커는 하나가 44pt라 열 개만 되어도 화면이
  /// 꽤 찬다.
  ///
  /// **화면에 동시에 보이는 상한이 아니다**(SPEC-0036, 사용자 정정 2026-09-18).
  /// 「이 지역 재검색」은 화면을 갈아 끼우지 않고 안 본 장소를 더하므로, 누를 때마다
  /// 10 → 20 → 30으로 늘어난다. 누적 상한은 두지 않는다 — 이름이 `maxDrawn`이던
  /// 시절의 「한 화면 상한」으로 읽으면 스펙과 정반대가 된다.
  ///
  /// **한 번 누를 때 더해지는 총수도 아니다.** 추천 spot과 문화행사를 별도 조회로
  /// 받아(FR-012) 각각 흡수하므로, 이 값은 그 **한 번의 흡수마다** 걸린다 — 한
  /// 번의 재검색으로 spot 10개와 행사가 함께 들어올 수 있다.
  static const int markersPerBatch = 10;

  /// 새 영역으로 볼 **중심 이동량** — 화면 크기에 대한 비율(사용자 결정 2026-09-18).
  ///
  /// 지도 중심이 직전 조회 중심에서 화면 폭·높이의 이만큼 이상 멀어지면 새 영역이다.
  /// 강남역 한 화면(폭 약 2km)에서 500m쯤 된다.
  ///
  /// **15%로 뒀다가 올렸다**(실기기 2026-09-18) — 자동 조회와 겹치니 생각보다 자주
  /// 불렸다. 한 번 부를 때마다 마커가 늘어나므로 조회 빈도가 곧 화면이 붐비는
  /// 속도다.
  ///
  /// **영역 포함 판정을 대신한다.** 예전에는 「화면이 직전 조회 영역 안에 완전히
  /// 들어있는가」로 봤는데, 조회 영역이 화면의 [viewportExpansion]배라 각 변에 10%
  /// 여백이 생겼다 — 화면의 10%를 밀면 판정이 바뀌었다.
  ///
  /// **그 값 자체는 크게 문제가 아니었다.** 실기기 지적(2026-09-18)의 「조금 벗어난
  /// 정도로는 데이터를 안 끌고 온다」는 판정이 둔감해서가 아니라, 판정이 참이어도
  /// **버튼만 띄우고 받아오지는 않았기** 때문이다. 그래서 자동 조회를 함께 넣었고
  /// (→[MapScreen]), 그 대신 조금 둔감하게 잡아 지도를 다듬는 동안 계속 조회되는
  /// 것을 막는다.
  ///
  /// **비율이라 줌과 무관하게 체감이 같다.** 절대 거리로 정하면 확대했을 때 화면이
  /// 좁아 같은 거리가 화면 여러 배가 되고, 축소하면 화면 안 움직임에도 걸린다.
  static const double areaChangeFraction = 0.25;

  /// 최소 조회 반경(km).
  ///
  /// 화면이 좁아도 이만큼은 받아 온다 — 확대해서 볼 때 화면 bbox만 보내면 눈앞의
  /// 몇 곳만 오는데, 사용자가 지도에서 보고 싶은 것은 "내 주변에 뭐가 있나"다.
  /// 결과는 어차피 격자로 솎아 스무 개 남짓만 그린다.
  static const double minQueryRadiusKm = 20;

  /// 혼잡도 조회의 최소 반경(km).
  ///
  /// **화면 bbox 그대로 보내면 확대했을 때 구역이 통째로 사라진다.** 서버는 구역
  /// **중심점**이 bbox 안에 드는지로 거르는데, 서울 열린데이터 POI는 120곳이
  /// 605km²에 흩어져 평균 간격이 2km가 넘는다. 확대해서 화면 폭이 1.3km쯤 되면
  /// 중심점이 하나도 안 걸려 `areas: []`가 온다 — 화면 한복판에 강남역 구역이
  /// 걸쳐 있어도 그렇다(실기기 실측 2026-08-25: 같은 강남 일대에서 폭 2km 요청은
  /// 3곳, 폭 1.3km 요청은 0곳).
  ///
  /// 3km면 어느 지점에서도 이웃 구역 몇 개의 중심을 담는다. **넓게 받아도 화면
  /// 밖은 어차피 안 보이므로** 그리기 쪽은 손대지 않는다 — 조회 범위만 넓힌다.
  ///
  /// 마커의 20km와 값이 다른 이유는 성격이 달라서다. 마커는 "주변에 뭐가 있나"라
  /// 넓을수록 좋지만, 혼잡도는 화면에 걸친 구역만 칠하면 되고 조회가 일일 쿼터를
  /// 쓴다(설계 §5.1) — 필요한 만큼만 넓힌다.
  static const double congestionMinRadiusKm = 3;

  /// 혼잡도 조회 bbox를 맞출 격자 크기(도).
  ///
  /// **캐시가 실제로 맞게 하는 값이다.** bbox를 그대로 캐시 키로 쓰면 지도를
  /// 1픽셀만 밀어도 소수점 아래가 달라져 매번 새 키가 된다 — 실기기에서 22초 동안
  /// 같은 강남 일대를 9번 조회했다(2026-08-25). 격자에 맞추면 같은 칸 안에서
  /// 움직이는 동안은 요청이 나가지 않는다.
  ///
  /// 0.05도는 위도로 약 5.5km, 서울 위도에서 경도로 약 4.4km다. 서울 전역이 위경도
  /// 0.3도 남짓이라 6×6칸 정도로 나뉜다 — 칸을 옮길 때만 새로 받는다.
  ///
  /// 크게 잡을수록 요청이 줄지만 한 번에 받는 범위가 넓어져 응답이 커진다.
  static const double congestionGridCell = 0.05;

  /// 혼잡도 결과를 붙들어 두는 시간.
  ///
  /// **원본이 실시간이 아니다.** 서울시 열린데이터의 관측 시각은 10분 단위로
  /// 떨어지고(실기기 로그 2026-08-25: `05:10`, `05:20`), 구역에 따라 몇 시간 전
  /// 값이 그대로 오기도 한다(`02:50`, `04:30`). 5분이면 그 사이에 값이 바뀌어도
  /// 한 주기 안에 따라잡는다.
  ///
  /// 사용자가 즉시 최신을 원할 때는 새로고침 버튼이 있다 — 자동 갱신 주기를
  /// 짧게 잡을 이유가 없다.
  static const Duration congestionCacheTtl = Duration(minutes: 5);

  /// "이 지역 재검색"을 다시 띄우기까지 기다리는 시간.
  ///
  /// 지도를 옮기지 않고 같은 화면에 머물러도 이 시간이 지나면 버튼을 다시 보여 준다
  /// (사용자 요청, 2026-08-10) — 같은 자리에서 **다음 장소**를 더 받아 보는 수단이다
  /// (SPEC-0036 FR-003).
  ///
  /// 조회 직후 곧바로 다시 띄우면 버튼이 깜빡이는 것처럼 보인다. 5초로 뒀다가
  /// 길게 느껴진다는 지적을 받아 3초로 줄였다(2026-08-10).
  static const Duration searchAgainDelay = Duration(seconds: 3);

  /// 메모리에 붙잡아 두는 마커 총량.
  ///
  /// [markersPerBatch]는 한 번에 **더해지는** 수이고, 이 값은 화면 밖으로 나간 것까지
  /// 포함해 메모리에 붙잡아 두는 총량이다. 축소하면 다시 보이므로 화면을 벗어났다고
  /// 바로 버리지 않는데, 그대로 두면 오래 돌아다닐수록 무한히 쌓인다.
  ///
  /// **표시 정책이 아니라 메모리 방어선이다**(SPEC-0036 D-05). 스펙은 누적 상한을
  /// 두지 않지만 그것은 「상한을 요구하지 않는다」이지 「메모리를 무한히 쓴다」가
  /// 아니다. 여기서 버려진 장소도 [MapMarkerController]의 제외 목록에는 남으므로
  /// 다시 후보가 되지는 않는다.
  ///
  /// **30개**(실기기 확인 2026-09-18, T4). 60개는 물론 40개도 강남 한 화면에서 사진
  /// 마커가 겹쳐 지도가 보이지 않았다.
  static const int maxRetainedMarkers = 30;


  /// 클러스터를 탭했을 때 한 번에 올리는 줌 단계(R22).
  ///
  /// 1단계씩 올리면 여러 번 탭해야 개별 마커에 닿아 답답하고, 크게 올리면 맥락을
  /// 잃는다. 잠정 2단계.
  static const int clusterTapZoomStep = 2;

  /// 검색으로 찾은 장소를 보여 줄 때의 줌.
  ///
  /// 넓게 열면 무엇을 찾았는지 알 수 없어 [initialZoom]보다 한 단계 조인다.
  static const int searchResultZoom = 16;

  /// 지도 첫 진입 시의 줌. 서울 도심에서 폴리곤이 바로 보이도록 [polygonMinZoom]
  /// 이상으로 둔다 — 진입 직후 혼잡도가 안 보이면 기능이 없는 것처럼 읽힌다.
  static const int initialZoom = 15;
}
