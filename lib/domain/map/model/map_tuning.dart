/// 지도 동작을 좌우하는 수치를 한곳에 모아 둔다. **전부 잠정값이다** —
/// spec §8의 미결 1·2·6·7번이며 실기기 측정으로 확정된다(설계 §9.2).
///
/// 한 파일에 모으는 이유는 측정 후 고칠 자리를 하나로 두기 위해서다. 값이 여러
/// 파일에 흩어지면 나중에 어느 것이 `[TBD]`였는지 되짚기 어렵다.
///
/// 확정되면 `[AMEND] SPEC-0014: ...`로 이슈에 회신한다.
abstract final class MapTuning {
  /// 유휴 판정 디바운스(R19). 지도가 멈춘 뒤 이 시간이 지나야 조회한다.
  ///
  /// 잠정 300ms — 손을 뗀 직후의 관성 스크롤이 잦아드는 데 통상 이 정도가 걸린다.
  /// 짧으면 관성 중에 조회가 나가 헛돌고, 길면 멈춘 뒤 빈 지도를 보는 시간이 늘어난다.
  static const Duration idleDebounce = Duration(milliseconds: 300);

  /// 뷰포트 확장 배율(R20). 화면 bbox를 이 배율로 넓혀 조회한다.
  ///
  /// 잠정 1.5배 — 화면 밖으로 각 변의 25%씩을 미리 받아 두면 작은 이동에 재조회가
  /// 걸리지 않는다. 넓힐수록 결과 수가 늘어 상한(R3)에 빨리 닿는 대가가 있다(설계 §3.2).
  static const double viewportExpansion = 1.5;

  /// 혼잡도 폴리곤을 그리는 최소 줌(R25).
  ///
  /// 렌더링 기준이자 **호출량 상한 장치**다. 이 값 미만에서는 `seoulCongestion`을
  /// 호출조차 하지 않는다(설계 §5.1) — 일일 쿼터 1000건을 지키는 실질적 수단이다.
  ///
  /// 잠정 14 — 구 단위가 화면에 들어오는 배율이다. 더 낮추면 서울 전역의 구역이 한
  /// 화면에 걸려 한 번에 수십 건을 조회하게 된다.
  static const int polygonMinZoom = 14;

  /// 서버가 클러스터를 내려주는 상한 줌(R2). 이 값 이하에서 클러스터가 오고 초과하면
  /// 개별 마커가 온다.
  ///
  /// **판정은 서버가 한다.** 클라이언트는 `spots`/`clusters` 중 채워진 쪽을 그릴
  /// 뿐이며(설계 §4.2), 이 값은 클러스터를 탭했을 때 어디까지 확대할지를 정하는 데
  /// 쓴다.
  static const int clusterMaxZoom = 13;

  /// 클러스터를 탭했을 때 한 번에 올리는 줌 단계(R22).
  ///
  /// 1단계씩 올리면 여러 번 탭해야 개별 마커에 닿아 답답하고, 크게 올리면 맥락을
  /// 잃는다. 잠정 2단계.
  static const int clusterTapZoomStep = 2;

  /// 지도 첫 진입 시의 줌. 서울 도심에서 폴리곤이 바로 보이도록 [polygonMinZoom]
  /// 이상으로 둔다 — 진입 직후 혼잡도가 안 보이면 기능이 없는 것처럼 읽힌다.
  static const int initialZoom = 15;
}
